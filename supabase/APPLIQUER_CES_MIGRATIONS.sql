-- ============================================================
-- RIEN À APPLIQUER POUR L'INSTANT
-- ============================================================
-- Ce fichier sert de point d'entrée unique : quand une migration est en
-- attente, son contenu est copié ici, prêt à coller dans l'éditeur SQL du
-- tableau de bord Supabase.
--
-- Pourquoi passer par un copier-coller plutôt que `supabase db push` :
-- 14 migrations appliquées à la main avant la mise en place de ce dépôt
-- n'ont pas de fichier local, et la CLI refuse de pousser tant que les deux
-- historiques divergent. Réparer ça est un chantier à part.
--
-- Appliquées et vérifiées en base :
--   20261001000000_tasks_completed_at       (completed_at)
--   20261002000000_tasks_category_source    (source_label, catégories)
--   20261012000000_email_analyses           (20 colonnes, RLS actif vérifié)
--
-- Piège rencontré : un copier-coller tronqué crée la table sans sa dernière
-- colonne, sans aucune erreur visible. Après chaque application, vérifier
-- que toutes les colonnes répondent, pas seulement que la table existe.
